#!/usr/bin/env node
// Generates testdata/interop/node-vectors.json: ciphertexts produced by the
// old stack's lib/encryption.ts algorithm, used as the "Node encrypts, Go
// decrypts" fixture. Reproduce with:
//   node server/scripts/interop/gen-node-vectors.mjs > server/testdata/interop/node-vectors.json
//
// The algorithm is copied verbatim from lib/encryption.ts (AES-256-CBC,
// key = sha256(secret + "-api-key-encryption"), hex, "iv:ct" / "v1:iv:ct").
import crypto from "crypto";

const ALGORITHM = "aes-256-cbc";

function getEncryptionKey(secret) {
  return crypto
    .createHash("sha256")
    .update(secret + "-api-key-encryption")
    .digest();
}

function encryptWithIv(secret, ivHex, text) {
  const iv = Buffer.from(ivHex, "hex");
  const cipher = crypto.createCipheriv(ALGORITHM, getEncryptionKey(secret), iv);
  return cipher.update(text, "utf8", "hex") + cipher.final("hex");
}

const secret = "interop-secret-42";
const apiKeyPlain = "sk-test-abcdef1234567890";
const apiKeyIv = "000102030405060708090a0b0c0d0e0f";
const credsJson = JSON.stringify({
  apiKey: "sk-cred-xyz",
  sk: "s3cr3t",
  workspaceId: "ws-1",
});
const credsIv = "0f0e0d0c0b0a090807060504030201ff";

const vectors = {
  _comment:
    "Generated by server/scripts/interop/gen-node-vectors.mjs from lib/encryption.ts's algorithm. Do not hand-edit.",
  secret,
  keyHex: getEncryptionKey(secret).toString("hex"),
  apiKeyPlain,
  apiKeyIv,
  apiKeyCipher: `${apiKeyIv}:${encryptWithIv(secret, apiKeyIv, apiKeyPlain)}`,
  credsJson,
  credsIv,
  credsCipher: `v1:${credsIv}:${encryptWithIv(secret, credsIv, credsJson)}`,
};

process.stdout.write(JSON.stringify(vectors, null, 2) + "\n");
